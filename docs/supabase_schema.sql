-- 1. Struktur tabel courses
CREATE TABLE IF NOT EXISTS public.courses (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code TEXT NOT NULL,
  title TEXT NOT NULL,
  credits INTEGER NOT NULL,
  status TEXT NOT NULL DEFAULT 'planned'
    CHECK (status IN ('planned', 'active', 'done')),
  user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Pastikan kolom user_id tersedia jika tabel sudah dibuat sebelumnya
ALTER TABLE public.courses
  ADD COLUMN IF NOT EXISTS user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL;

-- 2. Pastikan RLS diaktifkan pada tabel courses
ALTER TABLE public.courses ENABLE ROW LEVEL SECURITY;

-- 3. Hapus policy lama yang terlalu permisif agar tidak melewati pembatasan akses
DROP POLICY IF EXISTS "lab_allow_all_courses" ON public.courses;

-- Hapus policy yang mungkin sudah ada agar dapat diperbarui tanpa error duplikat
DROP POLICY IF EXISTS "courses_select_authenticated" ON public.courses;
DROP POLICY IF EXISTS "courses_insert_instructor_admin" ON public.courses;
DROP POLICY IF EXISTS "courses_update_instructor_admin" ON public.courses;
DROP POLICY IF EXISTS "courses_delete_instructor_admin" ON public.courses;

-- 4. Policy SELECT: Hanya pengguna terautentikasi (authenticated) yang dapat membaca data course
--    (Student, Instructor, dan Admin yang login dapat melihat seluruh course)
CREATE POLICY "courses_select_authenticated"
ON public.courses
FOR SELECT
TO authenticated
USING (true);

-- 5. Policy INSERT: Hanya Instructor dan Admin yang dapat membuat course
--    - Instructor HANYA boleh jika user_id sama dengan auth.uid()
--    - Admin dapat membuat course dengan user_id miliknya atau nilai lain
CREATE POLICY "courses_insert_instructor_admin"
ON public.courses
FOR INSERT
TO authenticated
WITH CHECK (
  EXISTS (
    SELECT 1 FROM public.profiles
    WHERE profiles.id = auth.uid()
      AND profiles.role = 'admin'
  )
  OR
  (
    user_id = auth.uid()
    AND EXISTS (
      SELECT 1 FROM public.profiles
      WHERE profiles.id = auth.uid()
        AND profiles.role = 'instructor'
    )
  )
);

-- 6. Policy UPDATE: Instructor hanya dapat mengubah course miliknya sendiri, Admin dapat mengubah semua course
